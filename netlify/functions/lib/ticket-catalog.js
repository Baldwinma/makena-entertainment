function getTicketDefinition(ticketId) {
    return ticketCatalog[ticketId] || null;
}

function getTicketTiers(ticket) {
    if (!ticket) {
        return [];
    }

    return (ticket.tiers && ticket.tiers.length ? ticket.tiers : [{
        id: 'general',
        name: 'General Admission',
        amount: ticket.amount,
        capacity: null,
        lowInventoryThreshold: 10
    }]).map(tier => ({
        ...tier,
        currency: ticket.currency
    }));
}

function getTierDefinition(ticketId, tierId) {
    const ticket = getTicketDefinition(ticketId);
    if (!ticket) {
        return null;
    }

    return getTicketTiers(ticket).find(tier => tier.id === tierId) || null;
}

function getTicketDefinitionByName(name) {
    const normalized = String(name || '').trim().toLowerCase();
    if (!normalized) {
        return null;
    }

    return Object.values(ticketCatalog).find(ticket => ticket.name.trim().toLowerCase() === normalized) || null;
}

function listTicketDefinitions() {
    return Object.entries(ticketCatalog).map(([id, ticket]) => ({
        id,
        ...ticket,
        tiers: getTicketTiers(ticket)
    }));
}

function summarizePurchasedItems(items) {
    if (!Array.isArray(items) || items.length === 0) {
        return '';
    }

    return items.map(item => {
        const quantity = item.quantity > 1 ? ` x${item.quantity}` : '';
        const tierName = item.tierName ? ` - ${item.tierName}` : '';
        return `${item.name}${tierName}${quantity}`;
    }).join(', ');
}

